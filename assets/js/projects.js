function renderProjects() {
    const container = document.querySelector(".project-container");
    if (!container) return;
    container.innerHTML = "";
    projectsData.forEach(project => {
        const projectBox = document.createElement("div");
        projectBox.classList.add("project-container-box", project.category);
        const techHtml = project.tech.map(tech => `
            <div class="technology-item">
                <img src="${tech.img}" alt="${tech.name}">
                <span>${tech.name}</span>
            </div>
        `).join("");

const linksHtml = project.links.map(link => {
    let icon = (link.label === 'Code' || link.label === 'General') 
        ? './assets/images/buttons/enlace.png' 
        : './assets/images/buttons/deploy-svgrepo-com.svg';
    if (link.type === "video" && link.url) {
        return `
            <a href="#" class="btn-play-video" data-video="${link.url}">
                <img class="info-btn-img" src="${icon}" alt="">
                ${link.label}
            </a>
        `;
    }
    return `
        <a href="${link.url}" target="_blank">
            <img class="info-btn-img" src="${icon}" alt="">
            ${link.label}
        </a>
    `;
}).join("");

        projectBox.innerHTML = `
            <div class="project-img-container" style="width:100%; overflow:hidden; border-radius:13px;">
                <img class="project-box-icon-clic-img" src="https://img.icons8.com/?size=100&id=23540&format=png&color=000000" alt="Project Icon" style="transition: opacity 0.5s ease-in-out;">
                <img class="project-box-img" src="${project.images[0]}" alt="${project.title}" style="transition: opacity 0.5s ease-in-out;">
            </div>
            <div class="project-box-info">
                <h4 class="project-box-info-title-h4">${project.title}</h4>
                <p>${project.description}</p>
                <div class="project-box-info-lenguajes">
                    ${techHtml}
                </div>
                <div class="project-box-info-btn">
                    ${linksHtml}
                </div>
            </div>
        `;
        container.appendChild(projectBox);

        const imgElement = projectBox.querySelector(".project-box-img");
        const imgContainer = projectBox.querySelector(".project-img-container");

        let intervalId;
        imgElement.style.cursor = "zoom-in";
        imgElement.addEventListener('click', () => {
            openLightbox(project.images, 0);
        });
        if (project.images.length > 1) {
            imgContainer.addEventListener("mouseenter", () => {
                let i = 0;

                project.images.forEach(src => {
                    const img = new Image();
                    img.src = src;
                });

                intervalId = setInterval(() => {
                    i = (i + 1) % project.images.length;
                    imgElement.style.opacity = 0;

                    setTimeout(() => {
                        imgElement.src = project.images[i];
                        imgElement.style.opacity = 1;
                    }, 200);
                }, 1000);
            });

            imgContainer.addEventListener("mouseleave", () => {
                clearInterval(intervalId);
                imgElement.style.opacity = 0;

                setTimeout(() => {
                    imgElement.src = project.images[0];
                    imgElement.style.opacity = 1;
                }, 200);
            });
        }
    });
    createLightbox();
    createVideoModal();

document.querySelectorAll(".btn-play-video").forEach(btn => {
    btn.addEventListener("click", (e) => {
        e.preventDefault();
        openVideoModal(btn.dataset.video);
    });
});
}

function createVideoModal() {
    if (document.getElementById("videoModal")) return;

    const modal = document.createElement("div");
    modal.id = "videoModal";
    modal.innerHTML = `
        <div class="video-overlay"></div>
        <div class="video-content">
            <span class="close-video">&times;</span>
            <iframe id="videoFrame" frameborder="0" allow="autoplay; encrypted-media" allowfullscreen></iframe>
        </div>
    `;

    document.body.appendChild(modal);

    modal.querySelector(".close-video").onclick = closeVideoModal;
    modal.querySelector(".video-overlay").onclick = closeVideoModal;
}

function openVideoModal(url) {
    const modal = document.getElementById("videoModal");
    const frame = document.getElementById("videoFrame");

    const videoId = url.includes("youtu.be") 
        ? url.split("/").pop().split("?")[0]
        : url.split("v=")[1]?.split("&")[0];

    frame.src = `https://www.youtube.com/embed/${videoId}?autoplay=1&rel=0`;

    modal.style.display = "flex";
    
    requestAnimationFrame(() => {
        modal.classList.add("active");
    });
}

function closeVideoModal() {
    const modal = document.getElementById("videoModal");
    const frame = document.getElementById("videoFrame");

    modal.classList.remove("active");

    setTimeout(() => {
        modal.style.display = "none";
        frame.src = "";
    }, 300);
}

